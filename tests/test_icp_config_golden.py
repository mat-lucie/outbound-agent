def test_score_prospect_matches_golden():
    """score_prospect output matches the regenerated golden for every fixture.

    Asserts an EXACT match on score, band, verdict_path, pass, persona,
    language, icp_lane, scoring_lane, and the full component breakdown for
    every fixture. A 1-point drift or verdict change fails here.
    """
    by_id = _fixtures_by_id()
    mismatches = []
    for fid, expected in GOLDEN.items():
        pdata, pcfg = by_id[fid]
        r = score_prospect(pdata, pcfg)
        actual = {
            "score": r["score"],
            "band": score_band(r["score"]),
            "verdict_path": r["verdict_path"],
            "pass": r["pass"],
            "persona": r["persona"],
            "language": r["language"],
            "icp_lane": r.get("icp_lane"),
            "scoring_lane": r["scoring_lane"],
            "breakdown": {k: v for k, v in r["score_breakdown"].items() if k != "reasons"},
        }
        if actual != expected:
            mismatches.append((fid, expected, actual))
    assert not mismatches, "Scoring drift vs the regenerated golden:\n" + "\n".join(
        f"  {fid}:\n    expected={exp}\n    actual  ={act}" for fid, exp, act in mismatches
    )


