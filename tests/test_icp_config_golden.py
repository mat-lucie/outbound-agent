"""Golden regression: ICP scoring is self-consistent against the reference operator.

The deterministic ICP inputs of ``workflows.quality_gate`` (keyword lists,
industry buckets, numeric weights, score bands, geography lists, disqualifier
families) are loaded from ``config/icp.yaml`` (here: the synthetic Acme operator
at ``examples/acme/config/icp.yaml``, via the conftest ``OUTBOUND_CONFIG_DIR``
pin) into ``ICPConfig``. The scoring MATH/LOGIC lives in code, not config.

BASELINE NOTE — the ``GOLDEN`` dict below was REGENERATED by running
``score_prospect`` over the fixture set under the synthetic Acme ICP. It is a
self-consistent regression guard on the scoring logic: a future change to the
scoring MATH (or to the Acme reference config) that shifts any score, band,
verdict-path, persona, lane, or breakdown component fails this test. It is NOT
the original post==pre-refactor equivalence proof — that proof ran against the
prior operator's real values and was retired with that data when the repo was
prepared for public release (see examples/acme/README.md).

Fixtures span the whole score space: decision-makers, the ops-in-industrial
joint case, off-ICP industries, sales-role + junior-IC hard disqualifiers,
company-keyed disqualifiers (PE, state-owned) and title-keyed ones
(HR/Finance/Innovation), academics, consultants, competitors, the global-exec
demote + its in-region override, all three scoring lanes (legacy / enterprise /
target_company), the low-confidence industry abstain, the S&OP exemption, the
ERP signal, unknown/blank inputs, and borderline-band fallback.
"""

