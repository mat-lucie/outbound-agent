class TestSkillMentionsExpectedCommand:
    """Smoke check: each SKILL.md mentions the cli subcommand it wraps.
    Cheap textual sanity — catches a SKILL that drifted from its
    Python entry point."""

    SKILL_TO_CLI: dict[str, str] = {
        "sales-daily": "sales daily",
        "sales-weekly": "sales weekly",
        "health-check": "sales health-check",
        "sales-finalize-borderline": "sales sales-finalize-borderline",
        "data-quality-report": "sales data-quality-report",
        "threshold-calibration": "sales threshold-calibration",
        "audit-reminder-sweep": "sales audit-reminder-sweep",
    }

    @pytest.mark.parametrize(
        "skill_name,expected_cli",
        sorted(SKILL_TO_CLI.items()),
    )
    def test_skill_references_its_cli_command(
        self, skill_name: str, expected_cli: str,
    ):
        text = (SKILLS_DIR / skill_name / "SKILL.md").read_text(encoding="utf-8")
        assert expected_cli in text, (
            f"skills/{skill_name}/SKILL.md must mention `{expected_cli}`"
        )
